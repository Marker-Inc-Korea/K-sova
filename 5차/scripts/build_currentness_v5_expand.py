def main():
    anchors, probes = [], []
    allf = FACTS + [SEATS]
    for i,(key, qs, ans, kws) in enumerate(allf):
        # 학습 앵커: 각 프레이밍 × 답변
        for q in qs:
            anchors.append({"tier":"fact","domain":"currentfacts","source_chunk":f"anchor:{key}",
                            "bucket":"CORE","anchor":True,
                            "messages":[{"role":"user","content":q},{"role":"assistant","content":ans}]})
        # 점검셋: 대표 질문 1개
        grade = "keyword" if len(kws)==1 or all(len(k)<=6 for k in kws) else "judge"
        probes.append({"qid":f"CPX{i:03d}","category":"최신성확장","instruction":qs[0],
                       "output":ans,"answer_keywords":kws,"kind":"current","grade":grade})
    ap = HERE/"anchor_currentfacts_v5expand.jsonl"; pp = HERE/"currentness_probe_v5expand.jsonl"
    with open(ap,"w") as f:
        for r in anchors: f.write(json.dumps(r,ensure_ascii=False)+"\n")
    with open(pp,"w") as f:
        for r in probes: f.write(json.dumps(r,ensure_ascii=False)+"\n")
    from collections import Counter
    print(f"[v5expand] 학습앵커 {len(anchors)}건 → {ap.name}")
    print(f"[v5expand] 점검셋 {len(probes)}건 → {pp.name}")
    cats={"개각/내각":sum(1 for k,*_ in allf if k.startswith('cab')),
          "지방선거":sum(1 for k,*_ in allf if k.startswith('local')),
          "정부조직":sum(1 for k,*_ in allf if k.startswith('org')),
          "사법검찰":sum(1 for k,*_ in allf if k=='prosecution'),
          "경제":sum(1 for k,*_ in allf if k.startswith('eco')),
          "인구사회":sum(1 for k,*_ in allf if k.startswith('pop') or k=='min_wage'),
          "대외":sum(1 for k,*_ in allf if k in('apec_2025','us_tariff')),
          "국회의석":1}
    print("  범주별 사실수:", cats, "총", len(allf), "사실")


if __name__=="__main__": main()
